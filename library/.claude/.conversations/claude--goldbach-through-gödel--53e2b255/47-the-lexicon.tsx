            <Paragraph>
                Arithmetic says infinity by absence — every number has a successor and none is last — and it names absence
                0. Held as a commitment, that is: the end of the number line, were there one, would be the number every
                prime divides, which arithmetic already calls 0. On every finite closed arithmetic the primes counted from
                either end pair symmetrically about every center. The commitment says that at the end there is only one end,
                so the two sieves are one, and the symmetric pairing reads: every even number is the sum of two primes. PA
                cannot derive this, because the derivation uses the closure every finite stage has and the limit lacks. So
                Goldbach's conjecture is not a fact PA is missing. It is the sentence in which PA's semantics of zero
                becomes a fact about the primes — what the semantics of zero says about the primes — and it is an axiom of
                the subject that holds that commitment, refutable by one even number, in which case the commitment, not PA,
                was wrong.
            </Paragraph>
